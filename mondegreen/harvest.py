def write_jsonl(pairs: Sequence[ErrorPair], path: str) -> None:
    """Write pairs as JSONL.

    Claim: SUPPORT.
    """
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        for p in pairs:
            fh.write(json.dumps(p.to_dict(), ensure_ascii=False) + "\n")


def read_jsonl(path: str) -> List[ErrorPair]:
    """Read pairs back from JSONL.

    Claim: SUPPORT.
    """
    out: List[ErrorPair] = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            d = json.loads(line)
            d["glossary_terms"] = tuple(d.get("glossary_terms", ()))
            d["error_types"] = tuple(d.get("error_types", ()))
            out.append(ErrorPair(**d))
    return out
