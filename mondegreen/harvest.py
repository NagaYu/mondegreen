"""Data construction: turn a real ASR system into an error generator.

Three builders, in the order the brief lays them out.

1. :class:`ErrorHarvester` -- take openly-licensed Japanese text, speak it with
   TTS under several voices, speeds, noise levels and room responses, run the
   result back through Whisper, and keep the ``(hypothesis, gold)`` pair.  The
   gold side is the text we fed to TTS, so it is exact by construction.  **No LLM
   grades anything, anywhere in this pipeline.**

2. :class:`PathologySet` -- deliberately reproduce the known failure modes:
   silence and noise-only regions that provoke canned hallucinations, dropped
   words, dropped particles, wrong numbers and units, and phonetic substitution
   of proper nouns.  Every pair carries a pathology label.

3. :class:`GlossaryBuilder` -- synthesise private vocabularies (people, products,
   jargon) *with readings*, write carrier sentences containing them, and push
   those through the same TTS -> ASR loop to manufacture "the term came back
   broken" cases at scale.

Licensing is not an afterthought here.  Every :class:`~mondegreen.types.ErrorPair`
records the corpus it came from and that corpus's licence, and
``scripts/harvest_errors.py`` refuses to push a dataset with an unset licence
field.  See :data:`CORPUS_LICENSES` -- and read it before adding a source, because
"Aozora Bunko" is not itself a licence.
"""

