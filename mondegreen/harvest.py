class ErrorHarvester:
    """Use a real ASR system as an error generator, or simulate one.

    ``mode="real"`` runs text -> TTS -> degradation -> Whisper.  ``mode="simulated"``
    runs the phonetic corruption model in :mod:`mondegreen.simulate`.  Both emit
    the same :class:`~mondegreen.types.ErrorPair` records, distinguished by their
    ``provenance`` field, and nothing downstream is allowed to mix them silently.

    Claim: SUPPORT -- this is the source of every number in the benchmark.
    """

    def __init__(
        self,
        tts: Optional[Callable[[str], Tuple[object, int]]] = None,
        asr: Optional[Callable[[object, int], str]] = None,
        degradations: Sequence[DegradationSpec] = DEFAULT_DEGRADATIONS,
        pathologies: Optional[PathologySet] = None,
        simulator: Optional[ASRErrorSimulator] = None,
        seed: int = 20260823,
    ) -> None:
        """Configure the harvester with TTS/ASR backends, or none for simulation.

                Claim: SUPPORT.
                """
        self.tts = tts
        self.asr = asr
        self.degradations = tuple(degradations)
        self.pathologies = pathologies or PathologySet()
        self.simulator = simulator or ASRErrorSimulator()
        self.seed = seed

    # ------------------------------------------------------------- simulated
    def harvest_simulated(
        self,
        sentences: Sequence[Tuple[str, Tuple[str, ...]]],
        glossary: Glossary,
        split: str = "train",
        corpus: str = "synthetic",
    ) -> List[ErrorPair]:
        """Generate pairs without any audio.

        Claim: SUPPORT.
        """
        lic = license_for(corpus)["license"]
        entries = list(glossary)
        out: List[ErrorPair] = []
        for i, (gold, terms) in enumerate(sentences):
            spec = self.degradations[i % len(self.degradations)]
            key = f"{split}-{i}"
            hyp, present, labels = self.simulator.corrupt(gold, entries, key=key)
            out.append(
                ErrorPair(
                    id=f"{corpus}-{split}-{i:06d}",
                    gold=gold,
                    hypothesis=hyp,
                    glossary_terms=present or terms,
                    error_types=labels,
                    speaker=f"sim-{i % 6}",
                    speed=spec.speed,
                    snr_db=spec.snr_db,
                    room=spec.room,
                    asr_model="simulated",
                    source_corpus=corpus,
                    source_license=lic,
                    split=split,
                    provenance="simulated",
                )
            )
        return out

    # ------------------------------------------------------------------ real
    def harvest_real(
        self,
        sentences: Sequence[Tuple[str, Tuple[str, ...]]],
        glossary: Glossary,
        split: str = "train",
        corpus: str = "synthetic",
        asr_model: str = "whisper",
        speakers: Sequence[str] = ("default",),
        progress: bool = True,
    ) -> List[ErrorPair]:
        """The real thing: speak each sentence, degrade it, transcribe it.

        Requires ``tts`` and ``asr`` callables (see :func:`build_tts` and
        :func:`build_asr`).  Raises rather than silently degrading to simulation,
        because a run that quietly stopped being real would poison the model card.

        Claim: SUPPORT.
        """
        if self.tts is None or self.asr is None:
            raise RuntimeError(
                "harvest_real needs both a TTS and an ASR backend. "
                "Install extras: pip install 'mondegreen[harvest,g2p]', or pass "
                "tts=/asr= explicitly. Refusing to fall back to simulation."
            )
        lic = license_for(corpus)["license"]
        out: List[ErrorPair] = []
        n = len(sentences)
        for i, (gold, terms) in enumerate(sentences):
            spec = self.degradations[i % len(self.degradations)]
            speaker = speakers[i % len(speakers)]
            wav, sr = self.tts(gold)
            wav = degrade(wav, sr, spec, seed=self.seed + i)
            hyp = self.asr(wav, sr)
            present = tuple(t for t in terms if t in gold)
            out.append(
                ErrorPair(
                    id=f"{corpus}-{split}-{i:06d}",
                    gold=gold,
                    hypothesis=hyp,
                    glossary_terms=present,
                    error_types=label_pair(gold, hyp, present),
                    speaker=speaker,
                    speed=spec.speed,
                    snr_db=spec.snr_db,
                    room=spec.room,
                    asr_model=asr_model,
                    source_corpus=corpus,
                    source_license=lic,
                    split=split,
                    provenance="measured",
                )
            )
            if progress and (i % 25 == 0 or i == n - 1):
                print(f"  harvest {split}: {i + 1}/{n}", flush=True)
        return out

    def harvest_hallucinations(
        self, split: str = "train", asr_model: str = "whisper", corpus: str = "synthetic"
    ) -> List[ErrorPair]:
        """Transcribe pure silence and noise, and keep whatever Whisper invents.

        Gold is the empty string, so every non-empty transcription is a
        hallucination with no judgement call involved.

        Claim: SUPPORT -- metric (5).
        """
        if self.tts is None or self.asr is None:
            raise RuntimeError("harvest_hallucinations needs a real ASR backend")
        import numpy as np

        lic = license_for(corpus)["license"]
        out: List[ErrorPair] = []
        sr = 16000
        for i, probe in enumerate(self.pathologies.silence_probes()):
            n = int(float(probe["seconds"]) * sr)
            if probe["kind"] == "silence":
                wav = np.zeros(n, dtype="float32")
            else:
                rng = np.random.default_rng(self.seed + i)
                wav = (rng.normal(0, 0.02, n)).astype("float32")
            hyp = self.asr(wav, sr)
            out.append(
                ErrorPair(
                    id=f"{corpus}-{split}-halluc-{i:04d}",
                    gold="",
                    hypothesis=hyp,
                    glossary_terms=(),
                    error_types=("hallucination",) if hyp.strip() else (),
                    speaker="none",
                    snr_db=probe.get("snr_db"),  # type: ignore[arg-type]
                    room="close",
                    asr_model=asr_model,
                    source_corpus=corpus,
                    source_license=lic,
                    split=split,
                    provenance="measured",
                )
            )
        return out


def label_pair(gold: str, hypothesis: str, terms: Sequence[str]) -> Tuple[str, ...]:
    """Assign pathology labels to a *measured* pair by comparing gold and hypothesis.

    Deterministic rules only -- string containment, length deltas, digit
    comparison, hallucination pattern matching.  No model decides a label.

    Claim: SUPPORT -- the labels have to be reproducible for the per-class
    breakdown to mean anything.
    """
    labels: List[str] = []
    for t in terms:
        if t and t not in hypothesis:
            labels.append("term-phonetic")
            break
    if len(hypothesis) < len(gold) * 0.85:
        labels.append("word-drop")
    gold_digits = re.findall(r"[0-9０-９]", gold)
    hyp_digits = re.findall(r"[0-9０-９]", hypothesis)
    if gold_digits != hyp_digits:
        labels.append("number-unit")
    for pat in DEFAULT_PATTERNS:
        if pat in hypothesis and pat not in gold:
            labels.append("hallucination")
            break
    if not labels and hypothesis != gold:
        labels.append("term-phonetic")
    return tuple(sorted(set(labels)))


