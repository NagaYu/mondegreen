@dataclass
class SentenceFactory:
    """Generate carrier sentences that contain glossary terms.

    The templates are deliberately meeting-shaped -- hedges, fillers, numbers,
    honorifics -- because those are the constructions a post-corrector is most
    likely to damage, and a corpus of clean declaratives would hide that.

    Claim: LOW-DAMAGE -- the evaluation corpus has to contain the things that are
    easy to break, or the damage rate is measured on easy mode.
    """

    seed: int = 20260823
    license_name: str = "CC0-1.0"
    corpus: str = "synthetic"

    def build(
        self,
        glossary: Glossary,
        n: int,
        seed: Optional[int] = None,
        terms_per_sentence: int = 2,
    ) -> List[Tuple[str, Tuple[str, ...]]]:
        """Return ``n`` ``(sentence, terms_used)`` pairs.

        Claim: TERM-RECALL.
        """
        rng = random.Random(self.seed if seed is None else seed)
        entries = list(glossary)
        if not entries:
            return []
        out: List[Tuple[str, Tuple[str, ...]]] = []
        for i in range(n):
            tpl = _TEMPLATES[rng.randrange(len(_TEMPLATES))]
            picks = [entries[rng.randrange(len(entries))] for _ in range(terms_per_sentence)]
            text = (
                tpl.replace("{T0}", picks[0].surface)
                .replace("{T1}", picks[min(1, len(picks) - 1)].surface)
                .replace("{N2}", str(rng.randint(1, 28)))
                .replace("{N}", str(rng.randint(2, 99)))
            )
            out.append((text, tuple(dict.fromkeys(p.surface for p in picks))))
        return out


