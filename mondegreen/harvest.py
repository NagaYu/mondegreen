@dataclass
class DegradationSpec:
    """One acoustic condition: speed, noise, room, band.

    Claim: SUPPORT -- ASR errors are a function of the channel, so the corpus has
    to span channels or it only measures one.
    """

    speed: float = 1.0
    snr_db: Optional[float] = None
    room: str = "close"       # close / far / reverb
    band: str = "wide"        # wide / telephone
    label: str = "clean"

    def to_dict(self) -> Dict[str, object]:
        """Claim: SUPPORT."""
        return asdict(self)


DEFAULT_DEGRADATIONS: Tuple[DegradationSpec, ...] = (
    DegradationSpec(1.00, None, "close", "wide", "clean"),
    DegradationSpec(1.15, 20.0, "close", "wide", "fast-clean"),
    DegradationSpec(0.90, 15.0, "close", "wide", "slow-noisy"),
    DegradationSpec(1.00, 10.0, "far", "wide", "far-field"),
    DegradationSpec(1.05, 5.0, "reverb", "wide", "reverb-noisy"),
    DegradationSpec(1.00, 12.0, "far", "telephone", "telephone"),
)


def degrade(audio, sample_rate: int, spec: DegradationSpec, seed: int = 0):
    """Apply a degradation spec to a waveform.

    Speed change by resampling, additive noise at a target SNR, a synthetic
    exponential-decay room impulse response for the far/reverb conditions, and a
    band-limit for the telephone condition.  Requires numpy; scipy is used for
    the filters when available.

    Claim: SUPPORT -- these are the conditions that generate the errors
    TERM-RECALL is measured on.
    """
    import numpy as np

    x = np.asarray(audio, dtype=np.float64)
    rng = np.random.default_rng(seed)

    if abs(spec.speed - 1.0) > 1e-3:
        n_out = int(len(x) / spec.speed)
        idx = np.linspace(0, len(x) - 1, n_out)
        x = np.interp(idx, np.arange(len(x)), x)

    if spec.room in ("far", "reverb"):
        rt60 = 0.35 if spec.room == "far" else 0.75
        n = int(rt60 * sample_rate)
        t = np.arange(n) / sample_rate
        rir = rng.normal(0, 1, n) * np.exp(-6.9 * t / rt60)
        rir[0] += 1.0
        rir /= np.sqrt(np.sum(rir ** 2)) or 1.0
        x = np.convolve(x, rir)[: len(x) + n - 1]
        if spec.room == "far":
            x *= 0.4

    if spec.band == "telephone":
        try:
            from scipy.signal import butter, sosfilt  # type: ignore

            sos = butter(4, [300 / (sample_rate / 2), 3400 / (sample_rate / 2)],
                         btype="band", output="sos")
            x = sosfilt(sos, x)
        except Exception:
            # Crude fallback band-limit: one-pole high pass + moving-average low pass.
            x = np.diff(np.concatenate([[0.0], x]))
            k = max(1, sample_rate // 6800)
            x = np.convolve(x, np.ones(k) / k, mode="same")

    if spec.snr_db is not None:
        sig_pow = float(np.mean(x ** 2)) or 1e-12
        noise = rng.normal(0, 1, len(x))
        noise_pow = float(np.mean(noise ** 2)) or 1e-12
        scale = math.sqrt(sig_pow / (noise_pow * (10 ** (spec.snr_db / 10.0))))
        x = x + scale * noise

    peak = float(np.max(np.abs(x))) or 1.0
    return (x / peak * 0.95).astype("float32")


