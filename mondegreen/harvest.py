def build_tts(backend: str = "auto", speaker: Optional[str] = None):
    """Return a ``text -> (waveform, sample_rate)`` callable.

    Backends tried in order: ``pyopenjtalk`` (offline, multiple voices via
    speed/pitch), ``voicevox`` (local HTTP server, many speakers), ``coqui``.

    Claim: SUPPORT -- LOCAL-SPEED is about inference; harvesting may use whatever
    it likes, but it must be reproducible and offline-capable.
    """
    order = ("pyopenjtalk", "voicevox", "coqui") if backend in ("auto", "") else (backend,)
    errors: List[str] = []
    for name in order:
        try:
            if name == "pyopenjtalk":
                import pyopenjtalk  # type: ignore

                def _tts(text: str):
                    """Synthesise one utterance -> (waveform, sample_rate).

                                        Claim: SUPPORT.
                                        """
                    wav, sr = pyopenjtalk.tts(text)
                    import numpy as np

                    return (np.asarray(wav, dtype="float32") / 32768.0), sr

                _tts.name = "pyopenjtalk"  # type: ignore[attr-defined]
                return _tts
            if name == "voicevox":
                import requests  # type: ignore

                base = os.environ.get("VOICEVOX_URL", "http://127.0.0.1:50021")
                sid = int(speaker or os.environ.get("VOICEVOX_SPEAKER", "1"))

                def _tts(text: str):
                    """Synthesise one utterance -> (waveform, sample_rate).

                                        Claim: SUPPORT.
                                        """
                    import io
                    import numpy as np
                    import soundfile as sf  # type: ignore

                    q = requests.post(f"{base}/audio_query", params={"text": text, "speaker": sid}, timeout=30)
                    q.raise_for_status()
                    s = requests.post(f"{base}/synthesis", params={"speaker": sid}, json=q.json(), timeout=120)
                    s.raise_for_status()
                    data, sr = sf.read(io.BytesIO(s.content), dtype="float32")
                    return np.asarray(data), sr

                _tts.name = f"voicevox:{sid}"  # type: ignore[attr-defined]
                return _tts
            if name == "coqui":
                from TTS.api import TTS  # type: ignore

                model = TTS(os.environ.get("COQUI_MODEL", "tts_models/ja/kokoro/tacotron2-DDC"))

                def _tts(text: str):
                    """Synthesise one utterance -> (waveform, sample_rate).

                                        Claim: SUPPORT.
                                        """
                    import numpy as np

                    wav = model.tts(text)
                    return np.asarray(wav, dtype="float32"), int(model.synthesizer.output_sample_rate)

                _tts.name = "coqui"  # type: ignore[attr-defined]
                return _tts
        except Exception as exc:
            errors.append(f"{name}: {type(exc).__name__}: {exc}")
    raise RuntimeError("no TTS backend available: " + "; ".join(errors))


def build_asr(model_size: str = "small", backend: str = "auto", language: str = "ja",
              initial_prompt: Optional[str] = None):
    """Return a ``(waveform, sample_rate) -> text`` callable.

    ``initial_prompt`` is how condition (B) is actually run: pass the glossary
    string and Whisper will silently truncate it to 244 tokens.

    Claim: UNBOUNDED-VOCAB -- this is the real measurement of the ceiling that
    :func:`~mondegreen.baselines.whisper_prompt_capacity` predicts.
    """
    order = ("faster_whisper", "whisper", "transformers") if backend in ("auto", "") else (backend,)
    errors: List[str] = []
    for name in order:
        try:
            if name == "faster_whisper":
                from faster_whisper import WhisperModel  # type: ignore

                model = WhisperModel(model_size, device="auto", compute_type="int8")

                def _asr(wav, sr):
                    """Transcribe one waveform -> text.

                                        Claim: SUPPORT.
                                        """
                    import numpy as np

                    audio = _resample(np.asarray(wav, dtype="float32"), sr, 16000)
                    segments, _ = model.transcribe(
                        audio, language=language, initial_prompt=initial_prompt,
                        condition_on_previous_text=False,
                    )
                    return "".join(s.text for s in segments).strip()

                _asr.name = f"faster-whisper-{model_size}"  # type: ignore[attr-defined]
                return _asr
            if name == "whisper":
                import whisper  # type: ignore

                model = whisper.load_model(model_size)

                def _asr(wav, sr):
                    """Transcribe one waveform -> text.

                                        Claim: SUPPORT.
                                        """
                    import numpy as np

                    audio = _resample(np.asarray(wav, dtype="float32"), sr, 16000)
                    r = model.transcribe(audio, language=language, initial_prompt=initial_prompt,
                                         condition_on_previous_text=False)
                    return str(r.get("text", "")).strip()

                _asr.name = f"whisper-{model_size}"  # type: ignore[attr-defined]
                return _asr
            if name == "transformers":
                from transformers import pipeline  # type: ignore

                pipe = pipeline("automatic-speech-recognition", model=f"openai/whisper-{model_size}")

                def _asr(wav, sr):
                    """Transcribe one waveform -> text.

                                        Claim: SUPPORT.
                                        """
                    import numpy as np

                    audio = _resample(np.asarray(wav, dtype="float32"), sr, 16000)
                    out = pipe(audio, generate_kwargs={"language": language})
                    return str(out.get("text", "")).strip()

                _asr.name = f"transformers-whisper-{model_size}"  # type: ignore[attr-defined]
                return _asr
        except Exception as exc:
            errors.append(f"{name}: {type(exc).__name__}: {exc}")
    raise RuntimeError("no ASR backend available: " + "; ".join(errors))


def _resample(x, sr_in: int, sr_out: int):
    """Linear resample; adequate for 16 kHz ASR front ends.

    Claim: SUPPORT.
    """
    import numpy as np

    if sr_in == sr_out:
        return x
    n = int(len(x) * sr_out / sr_in)
    return np.interp(np.linspace(0, len(x) - 1, n), np.arange(len(x)), x).astype("float32")


