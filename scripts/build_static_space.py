def main() -> int:
    """Claim: SUPPORT."""
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="hf/static_space")
    args = ap.parse_args()
    path = build(args.out)
    files = collect_files()
    print(f"wrote {path} ({os.path.getsize(path)/1024:.0f} KB, mondegreen v{__version__})")
    print(f"  {len(files)} files embedded, {sum(len(v) for v in files.values())/1024:.0f} KB of source+data")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
