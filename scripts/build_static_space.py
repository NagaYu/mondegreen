#!/usr/bin/env python3
"""Build a fully in-browser Hugging Face Space: Pyodide, no server, no framework.

Why not a normal Gradio Space
-----------------------------
Server-backed Gradio Spaces now require a paid plan. Static Spaces are free — and
for this project static is not a compromise, it is the honest deployment: the
Python runs in the visitor's browser, so a glossary of colleagues' names never
reaches Hugging Face's servers at all. "Nothing leaves your machine" stops being
a claim about how you deploy it and becomes a property of the page.

Why not gradio-lite
-------------------
Measured, not assumed: `@gradio/lite` 5.45 mounts but never starts Pyodide on an
HF static Space, because the page is not cross-origin isolated
(`SharedArrayBuffer` is undefined). The documented minimal example fails there
too, so this is not a markup problem. Plain Pyodide has no such requirement and
loads fine, so this builder drives Pyodide directly and renders the UI by hand.

That turns out better anyway: no framework bundle, a much faster first paint, and
the evidence panel is generated by :mod:`mondegreen.report` — the same code the
server-backed `app.py` uses, so the two frontends cannot drift.

The correction path has exactly one third-party dependency, numpy, which Pyodide
ships. `fugashi` is a C extension and is not available in the browser, so this
build falls back to the bundled 4,030-kanji reading table; the page says so
plainly, because without part-of-speech information the common-word protection
cannot fire and the damage rate is higher.

    python scripts/build_static_space.py --out hf/static_space
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from mondegreen import __version__
from mondegreen.report import CSS, EXAMPLE_GLOSSARY, EXAMPLE_TRANSCRIPT

#: Exactly the modules the correction path imports. Verified by walking the
#: import graph; training, benchmarking and runtime modules are absent.
PACKAGE_MODULES = (
    "__init__", "types", "phonetics", "reading", "glossary", "index",
    "gate", "hallucination", "corrector", "baselines", "report",
)
PYODIDE = "https://cdn.jsdelivr.net/pyodide/v0.28.3/full/"


def collect_files() -> dict:
    """Gather every file the browser filesystem needs, path -> text.

    Claim: SUPPORT.
    """
    files = {}
    for mod in PACKAGE_MODULES:
        path = os.path.join(REPO_ROOT, "mondegreen", f"{mod}.py")
        files[f"mondegreen/{mod}.py"] = open(path, encoding="utf-8").read()
    for name in ("kanji_readings.json", "common_kanji.json"):
        path = os.path.join(REPO_ROOT, "mondegreen", "data", name)
        files[f"mondegreen/data/{name}"] = open(path, encoding="utf-8").read()
    gate = os.path.join(REPO_ROOT, "models", "gate.json")
    if os.path.exists(gate):
        files["models/gate.json"] = open(gate, encoding="utf-8").read()
    return files


def build(out_dir: str) -> str:
    """Emit a single self-contained ``index.html``.

    Claim: LOCAL-SPEED -- the strongest available form of the claim: the code
    runs on the reader's machine, not on ours.
    """
    os.makedirs(out_dir, exist_ok=True)
    files = collect_files()
    payload = base64.b64encode(
        json.dumps(files, ensure_ascii=False).encode("utf-8")
    ).decode("ascii")

    html_doc = _PAGE.replace("__PAYLOAD__", payload)
    html_doc = html_doc.replace("__SHARED_CSS__", CSS)
    html_doc = html_doc.replace("__PYODIDE__", PYODIDE)
    html_doc = html_doc.replace("__VERSION__", __version__)
    html_doc = html_doc.replace("__EXAMPLE_TRANSCRIPT__", EXAMPLE_TRANSCRIPT)
    html_doc = html_doc.replace("__EXAMPLE_GLOSSARY__", EXAMPLE_GLOSSARY)

    out = os.path.join(out_dir, "index.html")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(html_doc)
    return out


